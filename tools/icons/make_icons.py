#!/usr/bin/env python3
"""Generate the app icon (adaptive vector) and the TV banner (PNG) from one design.

Design: a 2x2 grid of rounded camera tiles; the top-left tile carries a red "live" dot.

    python3 tools/icons/make_icons.py      # needs rsvg-convert (brew install librsvg)
"""
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"

BG = "#0F1720"
TILE = "#3B8EEA"
TILE_LIVE = "#7CC0FF"
LIVE_DOT = "#FF4D4D"


def rounded_rect(x, y, w, h, r):
    """SVG/VectorDrawable path for a rounded rectangle."""
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}"
            f"a{r},{r} 0 0 1 -{r},{r}h-{w - 2 * r}a{r},{r} 0 0 1 -{r},-{r}"
            f"v-{h - 2 * r}a{r},{r} 0 0 1 {r},-{r}z")


def circle(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 -{2 * r},0z"


def grid(x0, y0, tile, gap, radius):
    """Returns (live_tile_path, other_tiles_path, dot_path) for a 2x2 grid at (x0, y0)."""
    tiles = [rounded_rect(x0 + c * (tile + gap), y0 + r * (tile + gap), tile, tile, radius)
             for r in range(2) for c in range(2)]
    dot = circle(x0 + tile / 2, y0 + tile / 2, tile * 0.22)
    return tiles[0], "".join(tiles[1:]), dot


def vector(paths, size=108):
    body = "\n".join(
        f'    <path android:fillColor="{color}" android:pathData="{d}" />' for color, d in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icons/make_icons.py — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
{body}
</vector>
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


# --- Adaptive launcher icon: 108dp canvas, keep content inside the 66dp safe circle. ---
live, others, dot = grid(x0=31, y0=31, tile=21, gap=4, radius=4)
write(RES / "drawable/ic_launcher_foreground.xml",
      vector([(TILE_LIVE, live), (TILE, others), (LIVE_DOT, dot)]))
write(RES / "drawable/ic_launcher_background.xml",
      vector([(BG, "M0,0h108v108h-108z")]))
# Android 13+ themed icons: one colour, the system tints it.
write(RES / "drawable/ic_launcher_monochrome.xml",
      vector([("#FFFFFFFF", live + others)]))
write(RES / "mipmap-anydpi-v26/ic_launcher.xml", """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")

# --- TV banner: 320x180dp, rendered at xhdpi (640x360 px) with the app name. ---
live, others, dot = grid(x0=70, y0=110, tile=64, gap=12, radius=10)
svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360" viewBox="0 0 640 360">
  <rect width="640" height="360" fill="{BG}"/>
  <path d="{live}" fill="{TILE_LIVE}"/>
  <path d="{others}" fill="{TILE}"/>
  <path d="{dot}" fill="{LIVE_DOT}"/>
  <text x="252" y="196" font-family="Helvetica Neue" font-weight="bold" font-size="66" fill="#FFFFFF">Dahua TV</text>
  <text x="254" y="240" font-family="Helvetica Neue" font-size="26" fill="#9FB3C8">Camera wall · 4 live views</text>
</svg>
"""
svg_path = pathlib.Path(__file__).with_name("banner.svg")
write(svg_path, svg)
png = RES / "drawable-xhdpi/banner.png"
png.parent.mkdir(parents=True, exist_ok=True)
subprocess.run(["rsvg-convert", "-w", "640", "-h", "360", "-o", str(png), str(svg_path)], check=True)
print("wrote", png.relative_to(ROOT))
